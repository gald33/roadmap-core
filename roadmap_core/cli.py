# --- switchboard write exclusion ----------------------------------------------
#
# LEASE THE WRITE, NOT THE WORK.
#
# One item's claim state is asked three different questions, and a single
# long-lived lease used to answer all three badly. They are separated here:
#
#   "this item is mine for the next three days"  -> the committed item file.
#                                                   Durable. Never expires.
#   "nobody else read-modify-write this item     -> a Switchboard lease, held
#    while I am"                                    for SECONDS, below.
#   "am I still breathing on what I own"         -> roster/presence. Expiry is
#                                                   CORRECT there, not a bug.
#
# A lease means "a LIVE PROCESS holds this" — renewal is a side effect of the
# holder's heartbeat. Sized to the work rather than the write it stops being a
# lease and becomes a lock that survives its holder's death, which is the exact
# leaked claim Switchboard exists to eliminate, and it fails silently: a
# four-hour lease whose holder died in minute one blocks the item for the rest
# of the window and nothing ever asks.
#
# THE ROADMAP STORE STAYS THE ONLY AUTHORITY on who holds an item. This lease
# does not decide a claim and is never read back to validate one; it serializes
# the file write so two sessions cannot interleave a read-modify-write of the
# same YAML. Until the store is retired, Postgres still settles the cross-session
# race — this is the primitive that would replace it, proven in place first.
#
# Nothing here may block or fail a `claim`/`release`. Advisory: nudge dropped,
# roadmap claim wins. It degrades LOUDLY — every failure path prints — because a
# silent no-op is indistinguishable from working (this project's own CI
# announced nothing for a full day inside green builds, behind a `|| true`).
#
# Shells out to the `switchboard` CLI rather than re-implementing its HTTP calls,
# on purpose: every environment that runs `roadmap.py claim` interactively
# already has it (SessionStart hook, per CLAUDE.md).


def _switchboard_cli(
    *args: str, agent_id: str | None = None, timeout: float = 15.0
) -> subprocess.CompletedProcess | None:
    """Run one `switchboard` subcommand. Returns None if the CLI is not on
    PATH, if it errors, or if it does not answer in time — never raises, and
    never distinguishes those causes to the caller because none of them are
    actionable here beyond "the lease did not happen this time"."""
    if shutil.which("switchboard") is None:
        return None
    # An UNPINNED switchboard identity is derived from repo + branch + session,
    # so the working directory is part of who you are: shelling out from any cwd
    # other than the agent's repo root records the lease under a different id
    # than the agent announces as, and the lease is held by a ghost. Pin it —
    # see _switchboard_agent_id for why the pin must be per-session and NOT the
    # branch, and for how the reaper finds a holder instead.
    pin = ["--agent-id", agent_id] if agent_id else []
    try:
        return subprocess.run(
            # Global flags before the subcommand — the CLI does not accept
            # them after it (a documented gotcha this repo has hit more than
            # once; see CLAUDE.md's Switchboard section).
            ["switchboard", "--url", SWITCHBOARD_URL, "-w", SWITCHBOARD_WORKSPACE,
             *pin, *args],
            capture_output=True, text=True, timeout=timeout,
        )
    except (OSError, subprocess.SubprocessError):
        return None


def _switchboard_resource(key: str) -> str:
    return f"roadmap/{key}"


def _switchboard_agent_id() -> str:
    """A cwd-stable identity for this process's leases, DISTINCT per session.

    Both halves matter, and they pull against each other:

    *Stable* rules out letting the CLI derive one, because an unpinned identity
    includes the working directory — shelling out from a different cwd records
    the lease under an id the holder does not recognise as itself.

    *Distinct* rules out the obvious fix of pinning to the branch. Every session
    on that branch would then BE the same agent: sharing one read cursor, and
    able to release each other's leases — by construction, not by impersonation.
    That is the two-editor-tabs collision Switchboard's own session suffix exists
    to prevent, and it would land here as "my write lock vanished mid-write".

    So: honour the session's own pin when it has one, and otherwise mint an id
    that is unique to this process. Per-process is the right grain precisely
    because the lock is acquired and released inside one process — two concurrent
    `roadmap.py` runs SHOULD exclude each other, which is the whole point.

    Note this is not how the reaper will find a claim's holder. An agent id is
    session-scoped, so a session that legitimately restarts gets a new one and a
    multi-day claim would point at a dead id. Reconciliation runs through the
    branch, which the roster publishes as its own field and which survives a
    restart. This id is diagnostic detail; `claim.by` remains the key.
    """
    pinned = os.environ.get("SWITCHBOARD_AGENT_ID", "").strip()
    return pinned or f"roadmap-{current_branch()}-{os.getpid()}"


@contextlib.contextmanager
def switchboard_write_lock(key: str) -> Any:
    """Serialize the read-modify-write of `roadmap/items/<key>.yaml`.

    Acquired immediately before the write and released the moment it returns,
    so the lease is live for the duration of a file edit and not a working
    session. Best-effort throughout: a lock that cannot be taken is reported
    and the write proceeds, because the store has already decided the claim and
    an advisory layer must never turn a won claim into a failure.

    Takes no holder argument on purpose. The identity is this process's
    (`_switchboard_agent_id`), and letting a caller pass one is how it acquired
    a branch — i.e. an identity shared with every other session on that branch,
    each able to release the others' locks.
    """
    if not os.environ.get("SWITCHBOARD_TOKEN"):
        yield
        return
    resource = _switchboard_resource(key)
    who = _switchboard_agent_id()
    # The branch goes in the NOTE, never in the identity. A note is descriptive
    # and cannot collide; an identity is a key and can — two sessions sharing one
    # would be re-entrant for each other's locks, i.e. excluded from nothing, in
    # exactly the case this lock exists for. Carrying it here still gives anyone
    # reading `switchboard claims` (and §3's reaper, if it wants corroboration)
    # the link from a live lock back to the `claim.by` that owns the item.
    result = _switchboard_cli(
        "claim", resource,
        "--note", f"roadmap file write: {key} (claim.by={current_branch()})",
        "--ttl", str(SWITCHBOARD_LEASE_TTL),
        agent_id=who,
    )
    if result is None:
        print(
            "note: no switchboard write lock (CLI missing, unreachable, or timed out) "
            "— writing anyway; the store already settled this claim.",
            file=sys.stderr,
        )
    elif result.returncode != 0:
        print(
            f"note: could not take the switchboard write lock on {resource} "
            f"({result.stderr.strip() or result.stdout.strip() or 'unknown error'}). "
            f"Writing anyway — advisory only. If another session is mid-write on this "
            f"item, re-run `roadmap.py pull` afterwards and check the file.",
            file=sys.stderr,
        )
    try:
        yield
    finally:
        # Released immediately: holding it past the write is the very mistake
        # this section exists to undo. The TTL is only the ceiling for a session
        # that dies between the two calls.
        done = _switchboard_cli("release", resource, agent_id=who)
        if done is not None and done.returncode != 0:
            print(
                f"note: could not release the switchboard write lock on {resource} "
                f"({done.stderr.strip() or 'unknown error'}). It expires on its own "
                f"within {SWITCHBOARD_LEASE_TTL}s.",
                file=sys.stderr,
            )


