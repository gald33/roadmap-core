def _truncated_refs(text: str) -> list[str]:
    """Ref lines that YAML will silently cut short at an unquoted ``" #"``.

    `_yaml_scalar` quotes on `" #"` so anything *written* by this script is
    safe, but item files are also hand-authored, and there the loss is total
    and silent: `- PR #861` parses to `PR`, `validate` passes because it never
    inspects ref contents, and `diff` passes because it deliberately does not
    compare refs. Five refs reached prod that way on 2026-07-31.

    So this is checked against the raw text, before PyYAML has thrown the
    information away — by then there is nothing left to detect. Scoped to the
    ``refs:`` block: a ``#`` inside the ``evidence`` block scalar is literal
    and fine, which is why this cannot just scan the whole file.
    """
    bad: list[str] = []
    in_refs = False
    for line in text.splitlines():
        if not line.startswith((" ", "\t", "-")) and line.strip():
            in_refs = line.split(":", 1)[0].strip() == "refs"
            continue
        if not in_refs:
            continue
        entry = line.strip()
        if not entry.startswith("- "):
            continue
        scalar = entry[2:].strip()
        if scalar[:1] in ("'", '"'):
            continue
        if " #" in scalar:
            bad.append(scalar)
    return bad


def load_from_files() -> dict[str, dict[str, Any]]:
    """Parse ``roadmap/items/*.yaml``. Raises on the first malformed file — a
    half-loaded graph is worse than no graph."""
    try:
        import yaml
    except ImportError:  # pragma: no cover
        raise SystemExit("PyYAML required for --source files (pip install pyyaml)") from None
    by_key: dict[str, dict[str, Any]] = {}
    if not ITEMS_DIR.is_dir():
        return by_key
    for path in sorted(ITEMS_DIR.glob("*.yaml")):
        text = path.read_text()
        truncated = _truncated_refs(text)
        if truncated:
            raise SystemExit(
                f"{path}: ref(s) will silently truncate at ' #' — "
                + "; ".join(f"{s!r} loads as {s.split(' #', 1)[0]!r}" for s in truncated)
                + "\nQuote them: - 'PR #861'"
            )
        try:
            raw = yaml.safe_load(text) or {}
        except yaml.YAMLError as exc:
            raise SystemExit(f"{path}: invalid YAML: {exc}") from exc
        if not isinstance(raw, dict):
            raise SystemExit(f"{path}: expected a mapping at the top level")
        key = str(raw.get("id") or raw.get("key") or "")
        if key != path.stem:
            raise SystemExit(f"{path}: id {key!r} does not match filename stem {path.stem!r}")
        if not _ID_RE.match(key):
            raise SystemExit(f"{path}: id {key!r} is not kebab-case")
        claim = raw.get("claim") or {}
        by_key[key] = {
            "key": key,
            "title": str(raw.get("title") or ""),
            "status": str(raw.get("status") or "ready"),
            "arc": raw.get("arc"),
            "priority": raw.get("priority"),
            "claimed_by": claim.get("by"),
            "claimed_at": claim.get("at"),
            "blocked_on": list(raw.get("blocked_on") or []),
            "defer_reason": raw.get("defer_reason"),
            "related_to": list(raw.get("related_to") or []),
            "artifacts": list(raw.get("artifacts") or []),
            "refs": list(raw.get("refs") or []),
            "tickets": [str(t) for t in (raw.get("tickets") or [])],
            "evidence": raw.get("evidence") or "",
            "evidence_checked_at": raw.get("evidence_checked_at"),
        }
    return by_key


