#!/usr/bin/env python3
"""Roadmap work-item CLI — see ``roadmap/README.md``.

The store is the ``roadmap_items`` table, reached over the admin API. The
agent-facing artifact is ``roadmap/ROADMAP.md``, generated by ``sync`` and
committed, so a coding agent in a checkout can read the backlog with no DB
access, no admin JWT, and no network.

Two sources, one renderer:

  db     — the live graph via ``GET /admin/roadmap`` (needs LUCILLE_ADMIN_JWT)
  files  — ``roadmap/items/*.yaml``, the seed/offline authoring format

Both render through ``roadmap_core.graph``, loaded by path precisely so the CLI
needs none of the backend's dependencies. Same logic in the API and in the
markdown, or the file starts lying about what is ready.

The two sources drift, and the drift is invisible from either side alone:
``validate`` checks one source in isolation, and the CI sync guard compares two
*committed* artifacts that agree with each other while both disagree with the
store. So ``diff`` compares them directly and ``pull`` closes the gap the same
way ``push`` closes the other one.

Commands
    sync     regenerate roadmap/ROADMAP.md   (--source db|files)
    push     upload roadmap/items/*.yaml into the DB (prose + edges; NOT status)
    pull     write DB-only items + live claims back into roadmap/items/*.yaml
    diff     report where the DB and the committed files disagree
    prune    delete done items from the store AND the files (README rule 4)
    list     everything grouped by status
    ready    only what is startable now
    show     one item with its dependency chain
    claim    stake an item (one DB transaction — races cannot both win)
    status   move an item's status deliberately (the store owns that field)
    release  give it back
    validate schema, dangling deps, cycles

State fields — ``status`` and the claim — are the store's, and a file's value
for them is honored when the item is first filed and ignored afterwards. A
checkout is a snapshot; where an item *is* is not something a snapshot can
assert. ``push`` from files that predated a ``prune`` is what taught this: it
resurrected merged work as ``ready`` and silently un-started everything behind
it, because ``done`` is the one status the graph cannot re-derive.

``priority`` is NOT a state field. It is a judgement about what matters, so it is
authored in YAML, reviewed in a diff and uploaded by ``push`` — the same row of
the table as ``blocked_on`` and ``defer_reason``. It is the sort key ``ready``,
``list`` and the generated markdown all order by, ahead of the item key.
"""

