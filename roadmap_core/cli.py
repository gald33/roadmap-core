def _yaml_scalar(value: Any) -> str:
    """Quote only when the plain form would be ambiguous. Keeps hand-authored
    files looking hand-authored instead of machine-mangled."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    text = str(value)
    if text == "":
        return '""'
    risky = (
        text[0] in "-?:,[]{}#&*!|>'\"%@`"
        or ": " in text
        # " #" opens a YAML comment mid-scalar: an unquoted `PR #861` loads back
        # as `PR`. A ref silently losing its number is exactly the kind of quiet
        # corruption `pull` must not introduce.
        or " #" in text
        or text[-1] in " :"
    )
    if risky or text.strip() != text or text.lower() in ("null", "true", "false", "~"):
        return "'" + text.replace("'", "''") + "'"
    return text


def _claim_block(claim: dict[str, Any] | None) -> list[str]:
    """The `claim:` block, spelled the same way by every writer.

    Two writers reach here — `claim`'s projection and `pull` — and they used to
    disagree on precision for the *same* claim (seconds vs microseconds), so the
    same fact produced different bytes and the two paths conflicted in git. That
    cost a real merge conflict on #1087. `fmt_timestamp` is the same
    normalisation the renderer applies, so file and render now agree too.

    `at` stays quoted regardless: unquoted, PyYAML resolves an ISO timestamp to
    a datetime, and the file stops round-tripping as the string it was written
    as. Nothing compares `claimed_at` across sources — `diff` and `pull` both
    key on `claimed_by` — so normalising here cannot make either report a
    divergence that is not there.
    """
    if not claim or not claim.get("by"):
        return ["claim: null"]
    at = str(graph.fmt_timestamp(claim.get("at")) or "").replace("'", "''")
    return [
        "claim:",
        f"  by: {_yaml_scalar(claim['by'])}",
        f"  at: '{at}'",
    ]


def _replace_top_level_key(text: str, key: str, new_lines: list[str]) -> str:
    """Swap one top-level block of a YAML item file, leaving every other byte —
    including comments and the ``evidence`` block scalar — untouched.

    A whole-file round-trip through PyYAML would be shorter and would silently
    reformat files other sessions hand-wrote, dropping their comments. A claim is
    a one-field change; it should read as a one-field diff.
    """
    lines = text.splitlines()
    out: list[str] = []
    replaced = False
    i = 0
    while i < len(lines):
        line = lines[i]
        if not replaced and (line == f"{key}:" or line.startswith(f"{key}: ")):
            out.extend(new_lines)
            replaced = True
            i += 1
            # Swallow the old block's continuation lines (indented or list items).
            while i < len(lines) and (
                lines[i].startswith((" ", "\t")) or lines[i].startswith("- ")
            ):
                i += 1
            continue
        out.append(line)
        i += 1
    if not replaced:
        # Insert after the last of the leading identity keys, so the shape stays
        # id → title → status → arc → claim regardless of what the file had.
        anchor = 0
        for idx, line in enumerate(out):
            if line.split(":", 1)[0] in ("id", "title", "status", "arc", "priority"):
                anchor = idx + 1
        out[anchor:anchor] = new_lines
    return "\n".join(out).rstrip() + "\n"


def write_claim_to_file(key: str, claim: dict[str, Any] | None) -> bool:
    """Project a claim into the committed item file. Returns False if there is no
    file to write (a DB-only item — ``pull`` is what fixes that).

    The DB remains the race authority: this runs only *after* the claim
    transaction has already been won or lost. The file is a projection, and it
    exists because a claim otherwise changes no file, so — unlike an item edit —
    it never brings its own commit and no natural moment arrives at which anyone
    syncs it back.
    """
    path = item_path(key)
    if not path.is_file():
        return False
    path.write_text(_replace_top_level_key(path.read_text(), "claim", _claim_block(claim)))
    return True


def render_item_yaml(item: dict[str, Any]) -> str:
    """Emit a full item file, for an item that exists only in the DB."""
    lines = [
        f"id: {_yaml_scalar(item['key'])}",
        f"title: {_yaml_scalar(item.get('title') or '')}",
        f"status: {_yaml_scalar(item.get('status') or 'ready')}",
    ]
    if item.get("arc"):
        lines.append(f"arc: {_yaml_scalar(item['arc'])}")
    # Omitted when unset rather than written as `priority: null`: an absent
    # priority means nobody judged this item, and an explicit null in every file
    # would read as a judgement that was made and came out empty.
    if graph.priority_of(item):
        lines.append(f"priority: {_yaml_scalar(graph.priority_of(item))}")
    lines += _claim_block(
        {"by": item["claimed_by"], "at": item.get("claimed_at")}
        if item.get("claimed_by")
        else None
    )
    deps = list(item.get("blocked_on") or [])
    lines.append("blocked_on: []" if not deps else "blocked_on:")
    lines += [f"- {_yaml_scalar(d)}" for d in deps]
    defer_reason = (item.get("defer_reason") or "").strip()
    if defer_reason:
        lines.append("defer_reason: |")
        lines += [f"  {ln.rstrip()}".rstrip() for ln in defer_reason.splitlines()]
    # Emitted as a block mapping per edge, not inline flow, so a note can be
    # long without the line wrapping into unreadable YAML.
    relations = graph.normalize_relations(item)
    if relations:
        lines.append("related_to:")
        for rel in relations:
            lines.append(f"- key: {_yaml_scalar(rel['key'])}")
            if rel["note"]:
                lines.append(f"  note: {_yaml_scalar(rel['note'])}")
    artifacts = graph.normalize_artifacts(item)
    if artifacts:
        lines.append("artifacts:")
        lines += [f"- {_yaml_scalar(a)}" for a in artifacts]
    refs = list(item.get("refs") or [])
    if refs:
        lines.append("refs:")
        lines += [f"- {_yaml_scalar(r)}" for r in refs]
    # Before the evidence block scalar, like every other list field: anything
    # emitted after `evidence: |` would be swallowed into the prose.
    tickets = [str(t) for t in (item.get("tickets") or [])]
    if tickets:
        lines.append("tickets:")
        lines += [f"- {_yaml_scalar(t)}" for t in tickets]
    evidence = (item.get("evidence") or "").rstrip()
    if evidence:
        lines.append("evidence: |")
        lines += [f"  {ln.rstrip()}".rstrip() for ln in evidence.splitlines()]
    return "\n".join(lines) + "\n"


def _api(method: str, path: str, payload: dict | None = None) -> Any:
    """Call the admin API. Fails loudly with the server's message — a silent
    fallback to stale files would be worse than an error here."""
    token = os.environ.get("LUCILLE_ADMIN_JWT", "").strip()
    if not token:
        raise SystemExit(
            "LUCILLE_ADMIN_JWT is not set — needed for the db source.\n"
            "Mint one with the `mint-admin-jwt` skill, or use --source files."
        )
    base = os.environ.get("LUCILLE_BACKEND_URL", DEFAULT_BACKEND).rstrip("/")
    req = urllib.request.Request(
        f"{base}{path}",
        method=method,
        data=json.dumps(payload).encode() if payload is not None else None,
        headers={
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            body = resp.read().decode()
            return json.loads(body) if body else None
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode()[:400]
        raise SystemExit(f"{method} {path} -> HTTP {exc.code}: {detail}") from exc
    except urllib.error.URLError as exc:
        raise SystemExit(f"{method} {path} failed: {exc.reason}") from exc


def load_from_db() -> dict[str, dict[str, Any]]:
    data = _api("GET", "/admin/roadmap") or {}
    return {item["key"]: item for item in data.get("items", [])}


def load_pruned_keys(source: str = "db") -> frozenset[str]:
    """Keys a ``prune`` has spent. Empty rather than fatal when the store cannot
    answer: every caller uses this to SOFTEN a report, so failing closed here
    would turn an unreachable backend into a wall of false drift."""
    if source == "local":
        try:
            with store_for("local") as local:
                return local.pruned_keys()
        except SystemExit:
            return frozenset()
    try:
        data = _api("GET", "/admin/roadmap/prunes") or {}
    except SystemExit:
        return frozenset()
    return frozenset(p["key"] for p in data.get("prunes", []))


def load_from_local() -> dict[str, dict[str, Any]]:
    with store_for("local") as local:
        return local.items()


def load_arcs_from_local() -> dict[str, dict[str, Any]]:
    with store_for("local") as local:
        return local.arcs()


def load(source: str) -> dict[str, dict[str, Any]]:
    if source == "db":
        return load_from_db()
    if source == "local":
        return load_from_local()
    return load_from_files()


