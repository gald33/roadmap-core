def _repo_root() -> Path:
    """The project this CLI is driving.

    It used to be `__file__`'s grandparent, which was exactly right while the
    only copy of this file lived at `<repo>/scripts/roadmap.py`. Now the file
    ships inside the wheel, so `__file__` points into site-packages and that
    rule would resolve every path into somebody's virtualenv.

    So: an explicit `ROADMAP_REPO_ROOT` wins (Lucille's `scripts/roadmap.py`
    shim sets it, which is what keeps its layout working unchanged), then the
    nearest ancestor of the working directory that actually contains a
    `roadmap/` directory, then the working directory itself.

    Walking up matters more than it looks. `push` reports *"no item files to
    push"* when it is pointed at a directory that is not yours, which reads
    exactly like an empty backlog — so being run from a subdirectory would look
    like having nothing to do rather than like an error.
    """
    pinned = os.environ.get("ROADMAP_REPO_ROOT")
    if pinned:
        return Path(pinned).resolve()
    here = Path.cwd().resolve()
    # `roadmap/items` and `.git`, and deliberately NOT bare `roadmap/`.
    # `roadmap/` is a directory this tool CREATES — the store lands at
    # `roadmap/roadmap.db` — so keying on it means one command run from the
    # wrong directory mints the marker that makes that directory look like a
    # project root forever afterwards. Measured, not theorised: a single
    # `roadmap ready` in a subdirectory made every later command there resolve
    # to the subdirectory and read an empty backlog.
    #
    # Both markers are things a person makes: `roadmap/items` is where items
    # are authored, `.git` is where the project begins.
    for marker in (Path("roadmap") / "items", Path(".git")):
        for candidate in (here, *here.parents):
            if (candidate / marker).exists():
                return candidate
    return here


